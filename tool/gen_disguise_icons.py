"""Generates the disguise launcher icons for Android, iOS and web from one shape list.

Run from the repo root:  python tool/gen_disguise_icons.py   (needs Pillow)
All designs are original, built from circles and rounded rectangles on a 108x108
canvas (the Android adaptive-icon foreground grid; safe zone is the central 66).
"""
