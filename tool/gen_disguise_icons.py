def path_data(shape):
    if shape[0] == "c":
        _, cx, cy, r, _ = shape
        return f"M{cx - r},{cy} a{r},{r} 0 1,0 {2 * r},0 a{r},{r} 0 1,0 {-2 * r},0 Z"
    _, x, y, w, h, r, _ = shape
    if r == 0:
        return f"M{x},{y} h{w} v{h} h{-w} Z"
    return (f"M{x + r},{y} h{w - 2 * r} a{r},{r} 0 0,1 {r},{r} v{h - 2 * r} "
            f"a{r},{r} 0 0,1 {-r},{r} h{-(w - 2 * r)} a{r},{r} 0 0,1 {-r},{-r} "
            f"v{-(h - 2 * r)} a{r},{r} 0 0,1 {r},{-r} Z")


def write_android(kind, bg, shapes):
    paths = "\n".join(
        f'    <path android:fillColor="{s[-1]}" android:pathData="{path_data(s)}" />'
        for s in shapes)
    fg = RES / f"drawable/ic_disguise_{kind}_fg.xml"
    fg.parent.mkdir(parents=True, exist_ok=True)
    fg.write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tool/gen_disguise_icons.py -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp" android:height="108dp"\n'
        '    android:viewportWidth="108" android:viewportHeight="108">\n'
        f"{paths}\n</vector>\n", encoding="utf-8")
    adaptive = RES / f"mipmap-anydpi-v26/ic_launcher_{kind}.xml"
    adaptive.parent.mkdir(parents=True, exist_ok=True)
    adaptive.write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tool/gen_disguise_icons.py -->\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        f'    <background android:drawable="@color/ic_disguise_{kind}_bg" />\n'
        f'    <foreground android:drawable="@drawable/ic_disguise_{kind}_fg" />\n'
        f'    <monochrome android:drawable="@drawable/ic_disguise_{kind}_fg" />\n'
        '</adaptive-icon>\n', encoding="utf-8")
    # minSdk is 24: devices below API 26 get a rounded square with the same glyph.
    legacy = RES / f"mipmap-anydpi/ic_launcher_{kind}.xml"
    legacy.parent.mkdir(parents=True, exist_ok=True)
    legacy.write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tool/gen_disguise_icons.py -->\n'
        '<layer-list xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <item>\n'
        '        <shape android:shape="rectangle">\n'
        f'            <solid android:color="@color/ic_disguise_{kind}_bg" />\n'
        '            <corners android:radius="12dp" />\n'
        '        </shape>\n'
        '    </item>\n'
        f'    <item android:drawable="@drawable/ic_disguise_{kind}_fg" />\n'
        '</layer-list>\n', encoding="utf-8")


def render(bg, shapes, size, crop=(18, 90), rounded=False):
    """Draws the 108-grid region crop[0]..crop[1] into a size x size image."""
    ss = 4
    px = size * ss
    lo, hi = crop
    k = px / (hi - lo)
    img = Image.new("RGBA", (px, px), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if rounded:
        d.rounded_rectangle((0, 0, px - 1, px - 1), radius=px * 0.22, fill=bg)
    else:
        d.rectangle((0, 0, px, px), fill=bg)
    t = lambda v: (v - lo) * k
    for s in shapes:
        if s[0] == "c":
            _, cx, cy, r, col = s
            d.ellipse((t(cx - r), t(cy - r), t(cx + r), t(cy + r)), fill=col)
        else:
            _, x, y, w, h, r, col = s
            d.rounded_rectangle((t(x), t(y), t(x + w), t(y + h)), radius=r * k, fill=col)
    img = img.resize((size, size), Image.LANCZOS)
    return img if rounded else img.convert("RGB")  # iOS icons must be opaque


IOS_SIZES = [  # (idiom, size, scale)
    ("iphone", "60x60", 2), ("iphone", "60x60", 3),
    ("ipad", "76x76", 2), ("ipad", "83.5x83.5", 2),
    ("ios-marketing", "1024x1024", 1),
]


def write_ios(name, bg, shapes):
    folder = XCASSETS / f"{name}.appiconset"
    folder.mkdir(parents=True, exist_ok=True)
    images = []
    for idiom, size, scale in IOS_SIZES:
        px = round(float(size.split("x")[0]) * scale)
        filename = f"{name}-{px}.png"
        render(bg, shapes, px).save(folder / filename)
        images.append({"filename": filename, "idiom": idiom, "scale": f"{scale}x", "size": size})
    (folder / "Contents.json").write_text(
        json.dumps({"images": images, "info": {"author": "xcode", "version": 1}}, indent=2) + "\n",
        encoding="utf-8")


def main():
    colors = ['<?xml version="1.0" encoding="utf-8"?>',
              "<!-- Generated by tool/gen_disguise_icons.py -->", "<resources>"]
    for kind, (name, bg, shapes) in ICONS.items():
        colors.append(f'    <color name="ic_disguise_{kind}_bg">{bg}</color>')
        write_android(kind, bg, shapes)
        write_ios(name, bg, shapes)
        WEB_ICONS.mkdir(parents=True, exist_ok=True)
        render(bg, shapes, 64, rounded=True).save(WEB_ICONS / f"disguise-{kind}.png")
    colors.append("</resources>")
    (RES / "values/ic_disguise_colors.xml").write_text("\n".join(colors) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
